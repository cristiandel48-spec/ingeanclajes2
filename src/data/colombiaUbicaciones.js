// Helper para limpiar acentos y comparar de forma tolerante
export const limpiarTexto = (str = "") =>
  String(str)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();

// Descompone un string de ubicación (ej. "SABANETA-ANTIOQUIA" o "Sabaneta") en { departamento, municipio, manual, textoManual }
export const parsearUbicacion = (texto = "") => {
  if (!texto || typeof texto !== "string") {
    return { departamento: "Antioquia", municipio: "", manual: false, textoManual: "" };
  }

  const raw = texto.trim();
  const partes = raw.split(/[-–—,·]/).map((p) => p.trim()).filter(Boolean);

  if (partes.length >= 2) {
    const muniBuscado = limpiarTexto(partes[0]);
    const deptoBuscado = limpiarTexto(partes[1]);

    const deptoMatch = DEPARTAMENTOS_COLOMBIA.find(
      (d) =>
        limpiarTexto(d.nombre) === deptoBuscado ||
        deptoBuscado.includes(limpiarTexto(d.nombre)) ||
        limpiarTexto(d.nombre).includes(deptoBuscado)
    );

    if (deptoMatch) {
      const muniMatch = deptoMatch.municipios.find(
        (m) => limpiarTexto(m) === muniBuscado
      );
      if (muniMatch) {
        return { departamento: deptoMatch.nombre, municipio: muniMatch, manual: false, textoManual: "" };
      }
      return { departamento: deptoMatch.nombre, municipio: partes[0].toUpperCase(), manual: false, textoManual: "" };
    }
  }

  // Si solo viene una palabra, buscar en qué departamento está ese municipio
  const muniSolo = limpiarTexto(raw);
  for (const dep of DEPARTAMENTOS_COLOMBIA) {
    const muniMatch = dep.municipios.find((m) => limpiarTexto(m) === muniSolo);
    if (muniMatch) {
      return { departamento: dep.nombre, municipio: muniMatch, manual: false, textoManual: "" };
    }
  }

  // Si coincide directamente con el nombre de un departamento
  const depSolo = DEPARTAMENTOS_COLOMBIA.find((d) => limpiarTexto(d.nombre) === muniSolo);
  if (depSolo) {
    return { departamento: depSolo.nombre, municipio: "", manual: false, textoManual: "" };
  }

  return { departamento: "Antioquia", municipio: "", manual: true, textoManual: raw };
};
